// Builds the ClearPaid mobile app and desktop website from the shared screens.
//
// Edit the parts in freelancer/shared/ (common.html, views.html, mobile.html, desktop.html), then run:
//   node scripts/build-shells.js
// The generated pages live in freelancer/mobile/ and freelancer/desktop/. tests/shells.test.js fails
// if a generated page is out of date, so the two sites always show the same features.

const fs = require("fs");
const path = require("path");

const FREELANCER = path.join(__dirname, "..", "freelancer");
const SHARED = path.join(FREELANCER, "shared");

// One desktop page per screen. `view` must match data-view-panel and data-nav.
const SCREENS = [
  { view: "home", file: "index.html", title: "Overview" },
  { view: "invoices", file: "invoices.html", title: "Invoices" },
  { view: "scan", file: "scan.html", title: "Scan a bill" },
  { view: "projects", file: "projects.html", title: "Shared projects" },
  { view: "replies", file: "replies.html", title: "Client replies" },
  { view: "money", file: "money.html", title: "Rupees and ledger" },
  { view: "reminders", file: "reminders.html", title: "Reminders" },
  { view: "activity", file: "activity.html", title: "PayPal activity" }
];
const VIEWS = SCREENS.map(s => s.view);

const GENERATED_NOTE = "<!-- Generated by scripts/build-shells.js. Edit freelancer/shared/ instead, then run the build. -->";

function read(file) {
  return fs.readFileSync(path.join(SHARED, file), "utf8");
}

// Hides every screen except the one shown first, so the right screen is visible before any script runs.
function screensFor(views, shown) {
  return views.replace(/<section class="panel" data-view-panel="([a-z]+)">/g, (match, name) =>
    name === shown ? match : `<section class="panel hidden" data-view-panel="${name}">`);
}

// Function replacements keep "$" characters in the content from being read as replacement patterns.
function fill(html, tokens) {
  let out = html;
  for (const [token, value] of tokens) out = out.replace(token, () => value);
  return out.replace("<!doctype html>", "<!doctype html>\n" + GENERATED_NOTE);
}

function buildAll() {
  const common = read("common.html").trim();
  const views = read("views.html").trim();
  const mobileTemplate = read("mobile.html");
  const desktopTemplate = read("desktop.html");
  const out = new Map();

  out.set("mobile/index.html", fill(mobileTemplate, [
    ["<!-- COMMON -->", common],
    ["<!-- VIEWS -->", screensFor(views, "home")],
    ["__TITLE__", "ClearPaid"]
  ]));

  for (const s of SCREENS) {
    out.set("desktop/" + s.file, fill(desktopTemplate, [
      ["<!-- COMMON -->", common],
      ["<!-- VIEWS -->", screensFor(views, s.view)],
      ["__VIEW__", s.view],
      ["__TITLE__", `${s.title} · ClearPaid`]
    ]));
  }
  return out;
}

function writeAll() {
  const pages = buildAll();
  for (const [rel, html] of pages) {
    const file = path.join(FREELANCER, rel);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, html);
  }
  return [...pages.keys()];
}

module.exports = { buildAll, SCREENS, VIEWS, FREELANCER };

if (require.main === module) {
  const written = writeAll();
  console.log("Built " + written.length + " pages:");
  for (const rel of written) console.log("  freelancer/" + rel);
}
