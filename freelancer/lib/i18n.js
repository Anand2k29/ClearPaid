  const DICT = { en, hi };

  // Sets text for [data-i18n] and placeholders for [data-i18n-placeholder]. Missing keys keep the English text.
  function applyLang(doc, lang) {
    const table = DICT[lang] || DICT.en;
    doc.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      if (table[key]) el.textContent = table[key];
    });
    doc.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (table[key]) el.setAttribute("placeholder", table[key]);
    });
    doc.documentElement.lang = lang === "hi" ? "hi" : "en";
  }

  const api = { DICT, applyLang };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  else root.FreelancerI18n = api;
